#include "textflag.h"

// dot4vnni multiplies raw uint8 activations by four signed int8 weight rows.
// k is a positive multiple of 64; each ZMM lane accumulates four products.
TEXT ·dot4vnni(SB), NOSPLIT, $0-32
	MOVQ a+0(FP), BX
	MOVQ b+8(FP), SI
	MOVQ k+16(FP), DX
	MOVQ out+24(FP), DI
	LEAQ (SI)(DX*1), R8
	LEAQ (R8)(DX*1), R9
	LEAQ (R9)(DX*1), R10
	VPXORD Z8, Z8, Z8
	VPXORD Z9, Z9, Z9
	VPXORD Z10, Z10, Z10
	VPXORD Z11, Z11, Z11
	MOVL $0xffff, AX
	KMOVW AX, K1
	XORQ CX, CX
	vloop:
	VMOVDQU64 (BX)(CX*1), Z0
	VPDPBUSD (SI)(CX*1), Z0, K1, Z8
	VPDPBUSD (R8)(CX*1), Z0, K1, Z9
	VPDPBUSD (R9)(CX*1), Z0, K1, Z10
	VPDPBUSD (R10)(CX*1), Z0, K1, Z11
	ADDQ $64, CX
	CMPQ CX, DX
	JLT vloop
	VEXTRACTI64X4 $1, Z8, K1, Y0
	VPADDD Y0, Y8, Y8
	VEXTRACTI128 $1, Y8, X0
	VPADDD X0, X8, X8
	VPSHUFD $0x4e, X8, X0
	VPADDD X0, X8, X8
	VPSHUFD $0xb1, X8, X0
	VPADDD X0, X8, X8
	VMOVD X8, 0(DI)
	VEXTRACTI64X4 $1, Z9, K1, Y0
	VPADDD Y0, Y9, Y9
	VEXTRACTI128 $1, Y9, X0
	VPADDD X0, X9, X9
	VPSHUFD $0x4e, X9, X0
	VPADDD X0, X9, X9
	VPSHUFD $0xb1, X9, X0
	VPADDD X0, X9, X9
	VMOVD X9, 4(DI)
	VEXTRACTI64X4 $1, Z10, K1, Y0
	VPADDD Y0, Y10, Y10
	VEXTRACTI128 $1, Y10, X0
	VPADDD X0, X10, X10
	VPSHUFD $0x4e, X10, X0
	VPADDD X0, X10, X10
	VPSHUFD $0xb1, X10, X0
	VPADDD X0, X10, X10
	VMOVD X10, 8(DI)
	VEXTRACTI64X4 $1, Z11, K1, Y0
	VPADDD Y0, Y11, Y11
	VEXTRACTI128 $1, Y11, X0
	VPADDD X0, X11, X11
	VPSHUFD $0x4e, X11, X0
	VPADDD X0, X11, X11
	VPSHUFD $0xb1, X11, X0
	VPADDD X0, X11, X11
	VMOVD X11, 12(DI)
	VZEROUPPER
	RET
